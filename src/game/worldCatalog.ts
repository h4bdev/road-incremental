function makeCityRegion(
  regionId: string,
  regionName: string,
  bbox: [number, number, number, number],
  centerLat: number,
  centerLng: number,
  options?: {
    adminLevel?: string;
    isKnownIsland?: boolean;
    silhouette?: 'A' | 'B' | 'C';
    customRing?: Array<[number, number]>;
    customPolygons?: Array<Array<[number, number]>>;
  }
): Omit<ProvincialRegion, 'unlocked' | 'isStartingRegion' | 'isIsolated'> {
  const boundaryGeoJson: GeoJsonBoundary = options?.customPolygons
    ? { type: 'MultiPolygon', coordinates: options.customPolygons.map((ring) => [ring]) }
    : options?.customRing
    ? { type: 'Polygon', coordinates: [options.customRing] }
    : polyFromOffsets(
        bbox,
        options?.silhouette === 'B'
          ? SILHOUETTE_B
          : options?.silhouette === 'C'
          ? SILHOUETTE_C
          : SILHOUETTE_A
      );

  return {
    regionId,
    regionName,
    adminLevel: options?.adminLevel || '4',
    bbox,
    boundaryGeoJson,
    centerLat,
    centerLng,
    isKnownIsland: options?.isKnownIsland,
  };
}

