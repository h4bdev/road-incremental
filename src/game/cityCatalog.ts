/**
 * Fast client-side prefix and substring search on local catalog.
 * Guarantees that Korean & major world cities ALWAYS return immediate, accurate 1:1 coordinates.
 */
export function searchLocalCityCatalog(query: string, limit = 8): StartingCity[] {
  const norm = query.trim().toLowerCase().replace(/\s+/g, '');
  if (!norm) return [];

  const matches: Array<{ city: StartingCity; score: number }> = [];

  for (const item of COMPREHENSIVE_CITY_CATALOG) {
    const rawName = item.name.toLowerCase().replace(/\s+/g, '');
    const country = item.country.toLowerCase().replace(/\s+/g, '');
    let bestScore = 0;

    // Exact matches get highest score
    if (rawName === norm || item.aliases.some((a) => a.toLowerCase().replace(/\s+/g, '') === norm)) {
      bestScore = 100;
    } else if (
      rawName.startsWith(norm) ||
      item.aliases.some((a) => a.toLowerCase().replace(/\s+/g, '').startsWith(norm))
    ) {
      bestScore = 80;
    } else if (
      rawName.includes(norm) ||
      item.aliases.some((a) => a.toLowerCase().replace(/\s+/g, '').includes(norm))
    ) {
      bestScore = 60;
    } else if (country.includes(norm)) {
      bestScore = 30;
    }

    if (bestScore > 0) {
      const isPreset = ['seoul', 'busan', 'tokyo', 'newyork', 'london', 'paris'].includes(item.id.replace('kr_', '').replace('jp_', '').replace('us_', '').replace('uk_', '').replace('fr_', ''));
      matches.push({
        city: {
          id: item.id,
          name: item.name,
          country: item.country,
          lat: item.lat,
          lng: item.lng,
          zoom: item.zoom || 12,
          description: item.description,
          isCustom: !isPreset,
        },
        score: bestScore,
      });
    }
  }

  matches.sort((a, b) => b.score - a.score);
  return matches.slice(0, limit).map((m) => m.city);
}
