function polyFromOffsets(
  bbox: [number, number, number, number],
  normRing: Array<[number, number]>
): GeoJsonBoundary {
  const [minLat, minLng, maxLat, maxLng] = bbox;
  const latSpan = maxLat - minLat;
  const lngSpan = maxLng - minLng;
  const coords = normRing.map(([u, v]) => [
    Number((minLng + u * lngSpan).toFixed(5)),
    Number((minLat + v * latSpan).toFixed(5)),
  ]);
  // Ensure closed ring
  if (
    coords.length > 0 &&
    (coords[0][0] !== coords[coords.length - 1][0] ||
      coords[0][1] !== coords[coords.length - 1][1])
  ) {
    coords.push([...coords[0]]);
  }
  return {
    type: 'Polygon',
    coordinates: [coords],
  };
}

